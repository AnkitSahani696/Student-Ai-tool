package com.example.firebase
import android.content.Intent
import android.os.Bundle
import android.view.Menu
import android.view.MenuItem
import android.view.WindowManager
import androidx.appcompat.app.AppCompatActivity
import androidx.viewpager2.widget.ViewPager2
import com.example.firebase.databinding.ActivityQuestionsBinding
import com.google.android.material.tabs.TabLayoutMediator

class   QuestionsActivity : AppCompatActivity() {

    private lateinit var binding: ActivityQuestionsBinding
    private var pdfId: Long = -1
    private lateinit var pdfName: String

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        window.setFlags(
            WindowManager.LayoutParams.FLAG_FULLSCREEN,
            WindowManager.LayoutParams.FLAG_FULLSCREEN
        )
        binding = ActivityQuestionsBinding.inflate(layoutInflater)
        setContentView(binding.root)

        pdfId = intent.getLongExtra("PDF_ID", -1)
        pdfName = intent.getStringExtra("PDF_NAME") ?: "Questions"

        setupToolbar()
        setupViewPager()
    }

    private fun setupToolbar() {
        setSupportActionBar(binding.toolbar)
        supportActionBar?.title = pdfName
        supportActionBar?.setDisplayHomeAsUpEnabled(true)
    }

    private fun setupViewPager() {
        val adapter = QuestionsPagerAdapter(this, pdfId)
        binding.viewPager.adapter = adapter

        TabLayoutMediator(binding.tabLayout, binding.viewPager) { tab, position ->
            tab.text = when (position) {
                0 -> "Short Questions"
                1 -> "Long Questions"
                2 -> "MCQs"
                else -> ""
            }
        }.attach()
    }

    override fun onCreateOptionsMenu(menu: Menu?): Boolean {
        menuInflater.inflate(R.menu.menu_questions, menu)
        return true
    }

    override fun onOptionsItemSelected(item: MenuItem): Boolean {
        return when (item.itemId) {
            android.R.id.home -> {
                finish()
                true
            }
            R.id.action_share -> {
                shareQuestions()
                true
            }
            R.id.action_export -> {
                exportQuestions()
                true
            }
            R.id.action_delete -> {
                deleteQuestions()
                true
            }
            else -> super.onOptionsItemSelected(item)
        }
    }

    private fun shareQuestions() {
        val dbHelper = DatabaseHelper(this)
        val allQuestions = dbHelper.getAllQuestionsForPdf(pdfId)

        val shareText = buildString {
            append("📚 $pdfName - Questions\n\n")

            append("=== SHORT QUESTIONS ===\n\n")
            allQuestions.filter { it.type == "short" }.forEachIndexed { index, question ->
                append("${index + 1}. ${question.question}\n")
                append("Answer: ${question.answer}\n\n")
            }

            append("\n=== LONG QUESTIONS ===\n\n")
            allQuestions.filter { it.type == "long" }.forEachIndexed { index, question ->
                append("${index + 1}. ${question.question}\n")
                append("Answer: ${question.answer}\n\n")
            }

            append("\n=== MCQs ===\n\n")
            allQuestions.filter { it.type == "mcq" }.forEachIndexed { index, question ->
                append("${index + 1}. ${question.question}\n")
                question.options?.forEachIndexed { optIndex, option ->
                    val prefix = ('A' + optIndex)
                    append("$prefix) $option\n")
                }
                append("Correct Answer: ${question.answer}\n\n")
            }

            append("\n\n Generated by Question Generator App")
        }

        val shareIntent = Intent().apply {
            action = Intent.ACTION_SEND
            type = "text/plain"
            putExtra(Intent.EXTRA_TEXT, shareText)
            putExtra(Intent.EXTRA_SUBJECT, "$pdfName - Questions")
        }

        startActivity(Intent.createChooser(shareIntent, "Share Questions via"))
    }

