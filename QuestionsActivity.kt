        // Export as PDF or text file
        val dbHelper = DatabaseHelper(this)
        val allQuestions = dbHelper.getAllQuestionsForPdf(pdfId)

        // You can implement PDF export here using iText library
        // For now, we'll use simple text export

        android.widget.Toast.makeText(
            this,
            "Export feature coming soon! Use Share option for now.",
            android.widget.Toast.LENGTH_SHORT
        ).show()
    }

    private fun deleteQuestions() {
        com.google.android.material.dialog.MaterialAlertDialogBuilder(this)
            .setTitle("Delete Questions?")
            .setMessage("Kya aap ye questions delete karna chahte hain? Ye action undo nahi ho sakta.")
            .setPositiveButton("Delete") { _, _ ->
                val dbHelper = DatabaseHelper(this)
                dbHelper.deletePdf(pdfId)

                android.widget.Toast.makeText(
                    this,
                    "Questions deleted successfully",
                    android.widget.Toast.LENGTH_SHORT
                ).show()

                finish()
            }
            .setNegativeButton("Cancel", null)
            .show()
    }
}